    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {
        int selectedRow = tableTarefas.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma tarefa para editar", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int tarefaId = (int) tableTarefas.getValueAt(selectedRow, 0);
        Formulario f = new Formulario();
        f.setVisible(true);
        f.mostrarFormularioEdicao(tarefaId);
    }

    private void btnDeletarActionPerformed(java.awt.event.ActionEvent evt) {
        int selectedRow = tableTarefas.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma tarefa para deletar", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int tarefaId = (int) tableTarefas.getValueAt(selectedRow, 0);
        int confirm = JOptionPane.showConfirmDialog(this, "Deseja realmente deletar esta tarefa?", "Confirmação", JOptionPane.YES_NO_OPTION);
        
        if (confirm == JOptionPane.YES_OPTION) {
            
            dao.deletar(tarefaId);
            JOptionPane.showMessageDialog(this, "Tarefa deletada com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            atualizarTabela();
        }
    }

    private void btnLogoutActionPerformed(java.awt.event.ActionEvent evt) {
        int confirm = JOptionPane.showConfirmDialog(this, "Deseja fazer logout?", "Confirmação", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            Login login = new Login();
            login.setVisible(true);
            this.dispose();
        }
    }



