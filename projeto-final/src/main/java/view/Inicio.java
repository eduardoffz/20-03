    public void PreencherTabela() {
        model = (DefaultTableModel) tableTarefas.getModel();
        model.setRowCount(0);
        
        List<TarefaBean> tarefas = dao.listar();
        
        for(TarefaBean tarefa: tarefas) {
            Object[] linha = {
                tarefa.getId(),
                tarefa.getTitulo(),
                tarefa.getDescricao(),
                tarefa.getResponsavel(),
                tarefa.getStatus()
            };
            
            model.addRow(linha);
        }
    }
    
    
